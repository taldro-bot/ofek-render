def next_parasha():
    f = datetime.date.today(); f += datetime.timedelta(days=(4 - f.weekday()) % 7)   # the coming Friday (Saturday -> next week)
    u = 'https://www.hebcal.com/shabbat?cfg=json&geonameid=293397&M=on&lg=he&gy=%d&gm=%d&gd=%d' % (f.year, f.month, f.day)
    d = json.load(urllib.request.urlopen(urllib.request.Request(u, headers={'User-Agent': 'ofek-bot'}), timeout=30))
    for it in d.get('items', []):
        if it.get('category') == 'parashat':
            return it.get('hebrew', it.get('title', '')).replace('פרשת', '').strip()
    return ''


def new_job():
    name = next_parasha(); lines = P.get(name)
    if not lines: print('NO SUMMARY for', repr(name)); open('state/parasha_missing.txt', 'a').write(name + '\n'); return
    jid = 'r%s650' % datetime.date.today().strftime('%y%m%d')
    json.dump({'id': jid, 'title': 'פרשת %s בשתי דקות' % name, 'lines': lines, 'lang': 'he', 'kind': 'diary', 'typewriter': True,
               'parasha': name}, open('jobs/%s.json' % jid, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    open('state/pending.txt', 'a').write(jid + '\n'); print(jid, name)


if __name__ == '__main__' and sys.argv[1:] == ['new']: new_job()
